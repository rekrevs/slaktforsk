#!/usr/bin/env node
// Independent, manually reviewed structural baseline for the active pedigree.

import { readFileSync, readdirSync } from "node:fs";
import { join, resolve } from "node:path";

import { buildParentMap, deriveDepths } from "./lib/genealogy-relations.mjs";

const root = resolve(import.meta.dirname, "..");
const peopleDir = join(root, "genealogy", "people");
const people = new Map();
for (const name of readdirSync(peopleDir)) {
  const match = name.match(/^(P-\d{4})-/);
  if (!match) continue;
  people.set(match[1], { text: readFileSync(join(peopleDir, name), "utf8") });
}

// This list is reviewed from the person dossiers, not generated by the audit.
// 2026-08-29 (T-0012 batch 82): P-0058/P-0059 replaced by P-0422/P-0423 after
// C-0550 rejected the identification of P-0028 with Johan August Johansson.
// 2026-08-30 (T-0012 batch 126): C-0681 opened P-0470/P-0471 as the
// independently corroborated parents of P-0422.
// 2026-09-01 (T-0012 batch 166): C-0727 opened P-0472/P-0473 as the
// independently corroborated parents of P-0423.
// 2026-09-01 (T-0012 batch 168): C-0729 opened P-0474/P-0475 as the
// independently corroborated parents of P-0133.
// 2026-09-01 (T-0012 batch 170): C-0721/C-0731 opened P-0476/P-0477 as
// the independently corroborated parents of P-0475.
// 2026-09-01 (T-0012 batch 171): C-0733 opened P-0478/P-0479 as the
// independently corroborated parents of P-0473.
// 2026-09-02 (T-0012 batch 211): C-0798 opened P-0500 as the independently
// corroborated mother of P-0474; no father is inferred from Pehrsson.
// 2026-09-03 (T-0012 batch 229): PCD-2026-09-03-003 records the owner's
// 100-percent-certain knowledge that P-0001/P-0002 are P-0006's parents.
// Their OWNER_CONFIRMED links therefore remain established without being
// mislabelled as archival corroboration.
// 2026-09-03 (T-0012 batch 230): C-0820 opened P-0290/P-0289 as the
// independently corroborated parents of P-0020.
// Update this baseline deliberately when a source opens a new parent pair.
const expectedByDepth = new Map([
  [0, ["P-0004"]],
  [1, ["P-0005", "P-0006"]],
  [2, ["P-0001", "P-0002", "P-0003", "P-0007"]],
  [3, ["P-0009", "P-0010", "P-0015", "P-0016", "P-0028", "P-0029", "P-0048", "P-0049"]],
  [4, ["P-0020", "P-0021", "P-0042", "P-0043", "P-0050", "P-0051", "P-0422", "P-0423", "P-0065", "P-0066", "P-0094", "P-0095", "P-0110", "P-0111", "P-0133", "P-0134"]],
  [5, ["P-0102", "P-0103", "P-0123", "P-0124", "P-0125", "P-0126", "P-0131", "P-0132", "P-0145", "P-0148", "P-0158", "P-0159", "P-0214", "P-0215", "P-0230", "P-0231", "P-0289", "P-0290", "P-0329", "P-0330", "P-0470", "P-0471", "P-0472", "P-0473", "P-0474", "P-0475"]],
  [6, ["P-0149", "P-0160", "P-0161", "P-0162", "P-0163", "P-0164", "P-0165", "P-0166", "P-0221", "P-0222", "P-0232", "P-0233", "P-0234", "P-0235", "P-0266", "P-0267", "P-0476", "P-0477", "P-0478", "P-0479", "P-0500"]],
  [7, ["P-0226", "P-0227"]],
]);

const actualDepths = deriveDepths(buildParentMap(people), "P-0004");
let failed = false;
for (const [depth, expected] of expectedByDepth) {
  const actual = [...actualDepths]
    .filter(([, value]) => value === depth)
    .map(([id]) => id)
    .sort();
  const wanted = [...expected].sort();
  if (JSON.stringify(actual) !== JSON.stringify(wanted)) {
    failed = true;
    console.error(`Depth ${depth} mismatch`);
    console.error(`  expected: ${wanted.join(" ")}`);
    console.error(`  actual:   ${actual.join(" ")}`);
  }
}

const expectedIds = new Set([...expectedByDepth.values()].flat());
const unexpected = [...actualDepths.keys()].filter((id) => !expectedIds.has(id)).sort();
if (unexpected.length) {
  failed = true;
  console.error(`Unexpected derived ancestors: ${unexpected.join(" ")}`);
}

if (failed) process.exitCode = 1;
else console.log(`OK: independently reviewed pedigree structure matches ${actualDepths.size - 1} derived ancestors`);
