#!/usr/bin/env node
// Independent, manually reviewed structural baseline for the active pedigree.

import { readFileSync, readdirSync } from "node:fs";
import { join, resolve } from "node:path";

import { buildParentMap, deriveDepths } from "./lib/genealogy-relations.mjs";

const root = resolve(import.meta.dirname, "..");
const peopleDir = join(root, "genealogy", "people");
const people = new Map();
for (const name of readdirSync(peopleDir)) {
  const match = name.match(/^(P-\d{4})-/);
  if (!match) continue;
  people.set(match[1], { text: readFileSync(join(peopleDir, name), "utf8") });
}

// This list is reviewed from the person dossiers, not generated by the audit.
// Update it deliberately when a source opens a new parent pair.
const expectedByDepth = new Map([
  [0, ["P-0004"]],
  [1, ["P-0005", "P-0006"]],
  [2, ["P-0001", "P-0002", "P-0003", "P-0007"]],
  [3, ["P-0009", "P-0010", "P-0015", "P-0016", "P-0028", "P-0029", "P-0048", "P-0049"]],
  [4, ["P-0020", "P-0021", "P-0042", "P-0043", "P-0050", "P-0051", "P-0058", "P-0059", "P-0065", "P-0066", "P-0094", "P-0095", "P-0110", "P-0111", "P-0133", "P-0134"]],
  [5, ["P-0102", "P-0103", "P-0123", "P-0124", "P-0125", "P-0126", "P-0131", "P-0132", "P-0145", "P-0148", "P-0158", "P-0159", "P-0214", "P-0215", "P-0230", "P-0231", "P-0329", "P-0330"]],
  [6, ["P-0149", "P-0160", "P-0161", "P-0162", "P-0163", "P-0164", "P-0165", "P-0166", "P-0221", "P-0222", "P-0232", "P-0233", "P-0234", "P-0235", "P-0266", "P-0267"]],
  [7, ["P-0226", "P-0227"]],
]);

const actualDepths = deriveDepths(buildParentMap(people), "P-0004");
let failed = false;
for (const [depth, expected] of expectedByDepth) {
  const actual = [...actualDepths]
    .filter(([, value]) => value === depth)
    .map(([id]) => id)
    .sort();
  const wanted = [...expected].sort();
  if (JSON.stringify(actual) !== JSON.stringify(wanted)) {
    failed = true;
    console.error(`Depth ${depth} mismatch`);
    console.error(`  expected: ${wanted.join(" ")}`);
    console.error(`  actual:   ${actual.join(" ")}`);
  }
}

const expectedIds = new Set([...expectedByDepth.values()].flat());
const unexpected = [...actualDepths.keys()].filter((id) => !expectedIds.has(id)).sort();
if (unexpected.length) {
  failed = true;
  console.error(`Unexpected derived ancestors: ${unexpected.join(" ")}`);
}

if (failed) process.exitCode = 1;
else console.log(`OK: independently reviewed pedigree structure matches ${actualDepths.size - 1} derived ancestors`);
